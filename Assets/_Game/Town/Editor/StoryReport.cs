using System.IO;
using System.Linq;
using System.Text;
using Game.Characters.Content;
using Game.Characters.ContentAuthoring;
using Game.Characters.Generation;
using Game.Sim;
using Game.Sim.Relationships;
using Game.Sim.Sandbox;
using UnityEditor;
using UnityEngine;

namespace Game.Town
{
    /// <summary>
    /// Plays a month in three towns with the <see cref="AutoPlayer"/> and writes their diaries side by side
    /// (Docs/review/stories.md): evidence for "stories differ meaningfully by world seed" (PLAN.md §7, Phase 5 exit),
    /// and a quick read on pacing after any balance change.
    /// Headless: unity run . -- -executeMethod Game.Town.StoryReport.Write
    /// </summary>
    public static class StoryReport
    {
        const string Path = "Docs/review/stories.md";
        const int Days = 28;
        static readonly ulong[] Seeds = { 0x5EED, 2026, 777 };

        [MenuItem("Game/Town/Write Story Report")]
        public static void Write()
        {
            ContentCatalog characters = StandInContent.Load().LoadCatalog();
            SimCatalog sim = SimCatalog.FromJson(AssetDatabase.LoadAssetAtPath<TextAsset>("Assets/_Game/Sim/Content/SimCatalog.json").text);

            var report = new StringBuilder();
            report.AppendLine("# Four weeks in three towns");
            report.AppendLine();
            report.AppendLine($"_Generated by `StoryReport` ({nameof(AutoPlayer)}, {Days} days per town). An attentive automated player: it works when money is short, says hi to new faces, spends time with whoever it likes most, gives fitting gifts, asks them out somewhere they'd enjoy, and shops on Saturdays._");
            report.AppendLine();

            foreach (ulong seed in Seeds)
            {
                SimWorld world = new TownGenerator(sim, characters).Create(seed);
                world.Player.Name = "Kit";
                world.Player.Dna = new CharacterGenerator(characters).Generate(seed + 1);
                world.Player.Location = SimCatalog.Home;
                world.Now = SimTime.At(0, 8);
                var player = new AutoPlayer(new TownSession(world), seed);
                player.PlayDays(Days);

                var met = world.Relationships.Where(r => r.Met).ToList();
                report.AppendLine($"## Town {seed:x}");
                report.AppendLine();
                report.AppendLine($"- **Met:** {met.Count} of {world.Residents.Count} residents");
                report.AppendLine($"- **Friends or closer:** {string.Join(", ", met.Where(r => r.Stage >= Stage.Friend).Select(r => $"{world.Residents[r.Resident].Name} ({r.Stage})"))}");
                report.AppendLine($"- **Dates:** {met.Sum(r => r.Dates)}, with {string.Join(", ", met.Where(r => r.Dates > 0).Select(r => world.Residents[r.Resident].Profile.FirstName))}");
                report.AppendLine($"- **Town couples that changed:** {world.Social.Events.Count}");
                report.AppendLine($"- **Coins left:** {world.Player.Money}");
                report.AppendLine();
                report.AppendLine("<details><summary>Diary</summary>");
                report.AppendLine();
                foreach (string line in player.Diary) report.AppendLine("- " + line);
                report.AppendLine();
                report.AppendLine("</details>");
                report.AppendLine();
            }

            File.WriteAllText(Path, report.ToString().Replace("\r\n", "\n"));
            Debug.Log("[StoryReport] Wrote " + Path);
        }
    }
}
